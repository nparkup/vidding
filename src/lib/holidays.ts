/**
 * 한국 공휴일 (대체공휴일 포함). 매년 말 다음 해 목록을 추가해야 한다.
 * 장기적으로는 공공데이터포털 '한국천문연구원_특일 정보' API로 대체 가능.
 */
const HOLIDAYS = new Set([
  // 2026
  "2026-01-01", "2026-02-16", "2026-02-17", "2026-02-18", "2026-03-02", "2026-05-05", "2026-05-25",
  "2026-06-03", "2026-08-17", "2026-09-24", "2026-09-25", "2026-09-28", "2026-10-05", "2026-10-09", "2026-12-25",
  // 2027
  "2027-01-01", "2027-02-08", "2027-02-09", "2027-03-01", "2027-05-05", "2027-05-13", "2027-08-16",
  "2027-09-14", "2027-09-15", "2027-09-16", "2027-10-04", "2027-10-11", "2027-12-27",
]);

/** KST 기준 YYYY-MM-DD 와 요일(0=일) */
export function kstDay(d = new Date()) {
  const k = new Date(d.getTime() + 9 * 3600 * 1000);
  return { ymd: k.toISOString().slice(0, 10), dow: k.getUTCDay(), hour: k.getUTCHours() };
}

export function isBusinessDay(d = new Date()): boolean {
  const { ymd, dow } = kstDay(d);
  return dow !== 0 && dow !== 6 && !HOLIDAYS.has(ymd);
}
